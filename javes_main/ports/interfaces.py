"""Application ports. Concrete adapters may be local, HTTP, queue, or DB based."""

from __future__ import annotations

from datetime import datetime
from typing import ContextManager, Protocol

from javes_contracts import (
    ClipRecord,
    ClipStateCommand,
    CutClipCommand,
    ExportClipsCommand,
    ExportClipsResult,
    PerceptionProbeJob,
    ProbeResult,
    RetentionCommand,
    RetentionResource,
    RetentionResult,
    RoutingWorkerResult,
    SearchState,
    SiteGraph,
    TargetGalleryCommand,
    TargetGalleryResult,
    VideoSegmentRequest,
    VideoSegmentResult,
)
from routing.contracts import Anchors
from routing.contracts.params import RoutingParams

from javes_main.domain.models import (
    AuditEvent,
    AuthSession,
    CaseDataRecord,
    CaseRecord,
    JobRecord,
    OutboxRecord,
    ProbeResultRecord,
    RoutingTriggerRecord,
    UserAccount,
)


class Clock(Protocol):
    def now(self) -> datetime: ...


class IdGenerator(Protocol):
    def new(self, prefix: str, *parts: object) -> str: ...


class CaseRepository(Protocol):
    def transaction(self) -> ContextManager[CaseRepository]: ...
    def add(self, case: CaseRecord) -> None: ...
    def get(self, case_id: str) -> CaseRecord: ...
    def list_cases(self, *, lifecycles: set[str] | None = None) -> list[CaseRecord]: ...
    def save(self, case: CaseRecord, expected_revision: int) -> CaseRecord: ...
    def add_job(self, job: JobRecord) -> None: ...
    def get_job(self, job_id: str) -> JobRecord: ...
    def save_job(self, job: JobRecord) -> None: ...
    def list_jobs(self, case_id: str, *, states: set[str] | None = None) -> list[JobRecord]: ...
    def claim_jobs(
        self,
        *,
        worker_id: str,
        now: datetime,
        lease_expires_at: datetime,
        limit: int,
        case_id: str | None = None,
    ) -> list[JobRecord]: ...
    def reclaim_expired_jobs(self, *, now: datetime) -> list[JobRecord]: ...
    def append_event(self, event: AuditEvent) -> None: ...
    def list_events(self, case_id: str) -> list[AuditEvent]: ...
    def remember_idempotency(self, key: str, fingerprint: str, response: dict) -> None: ...
    def get_idempotency(self, key: str) -> tuple[str, dict] | None: ...
    def lock_idempotency(self, key: str) -> None: ...
    def add_user(self, user: UserAccount) -> None: ...
    def get_user(self, user_id: str) -> UserAccount: ...
    def get_user_by_username(self, username: str) -> UserAccount: ...
    def save_user(self, user: UserAccount) -> None: ...
    def list_users(self) -> list[UserAccount]: ...
    def add_session(self, session: AuthSession) -> None: ...
    def get_session_by_token_hash(self, token_hash: str) -> AuthSession | None: ...
    def save_session(self, session: AuthSession) -> None: ...
    def revoke_user_sessions(self, user_id: str, *, now: datetime) -> int: ...
    def add_outbox(self, message: OutboxRecord) -> None: ...
    def get_outbox(self, message_id: str) -> OutboxRecord: ...
    def list_outbox(
        self, *, case_id: str | None = None, states: set[str] | None = None
    ) -> list[OutboxRecord]: ...
    def save_outbox(self, message: OutboxRecord) -> None: ...
    def claim_outbox(
        self,
        *,
        worker_id: str,
        now: datetime,
        lease_expires_at: datetime,
        limit: int,
    ) -> list[OutboxRecord]: ...
    def reclaim_expired_outbox(self, *, now: datetime) -> list[OutboxRecord]: ...
    def add_probe_result(self, record: ProbeResultRecord) -> bool: ...
    def list_probe_results(self, case_id: str) -> list[ProbeResultRecord]: ...
    def add_case_data(self, record: CaseDataRecord) -> None: ...
    def list_case_data(
        self, case_id: str, *, kinds: set[str] | None = None
    ) -> list[CaseDataRecord]: ...
    def add_routing_trigger(self, trigger: RoutingTriggerRecord) -> None: ...
    def get_routing_trigger(self, trigger_id: str) -> RoutingTriggerRecord: ...
    def save_routing_trigger(self, trigger: RoutingTriggerRecord) -> None: ...
    def list_routing_triggers(
        self, *, case_id: str | None = None, states: set[str] | None = None
    ) -> list[RoutingTriggerRecord]: ...
    def claim_routing_triggers(
        self,
        *,
        worker_id: str,
        now: datetime,
        lease_expires_at: datetime,
        limit: int,
    ) -> list[RoutingTriggerRecord]: ...
    def reclaim_expired_routing_triggers(
        self, *, now: datetime
    ) -> list[RoutingTriggerRecord]: ...
    def purge_case_content(
        self, case_id: str, *, preserve_outbox_message_id: str | None = None
    ) -> None: ...
    def redact_case_data(self, case_id: str, *, kinds: set[str]) -> None: ...
    def purge_search_content(
        self, case_id: str, *, preserve_outbox_message_id: str | None = None
    ) -> None: ...


class ArtifactStore(Protocol):
    def put(self, key: str, data: bytes, mime_type: str) -> str: ...
    def get(self, key: str) -> tuple[bytes, str]: ...
    def delete(self, key: str) -> bool: ...


class LiveFeedPort(Protocol):
    """Reads an opaque, short-lived stream reference produced by Perception."""

    def get(self, stream_ref: str) -> tuple[bytes, str]: ...


class SiteConfigPort(Protocol):
    def get_graph(self, site_id: str, version: str) -> SiteGraph: ...
    def get_floor_assets(self, site_id: str, version: str) -> dict[str, bytes]: ...
    def get_params(self, version: str | None = None) -> RoutingParams: ...


class RoutingPort(Protocol):
    def initialise(self, case, graph: SiteGraph, params: RoutingParams) -> SearchState: ...
    def advance(
        self,
        state: SearchState,
        probe_results: list[ProbeResult],
        graph: SiteGraph,
        anchors: Anchors,
        params: RoutingParams,
        now: datetime,
        floor_assets: dict[str, bytes],
    ) -> RoutingWorkerResult: ...


class PerceptionPort(Protocol):
    def update_gallery(self, command: TargetGalleryCommand) -> TargetGalleryResult: ...
    def execute(self, job: PerceptionProbeJob, now: datetime) -> ProbeResult: ...
    def cancel(self, job: PerceptionProbeJob, now: datetime) -> ProbeResult: ...


class ClipPort(Protocol):
    def cut(self, command: CutClipCommand) -> ClipRecord: ...
    def change_state(self, command: ClipStateCommand) -> ClipRecord: ...
    def export(self, command: ExportClipsCommand) -> ExportClipsResult: ...


class RetentionPort(Protocol):
    def register(self, resource: RetentionResource) -> None: ...
    def process(self, command: RetentionCommand) -> RetentionResult: ...


class VideoArchivePort(Protocol):
    def get_segment(
        self, request: VideoSegmentRequest, *, now: datetime
    ) -> VideoSegmentResult: ...
